CREATE TABLE IF NOT EXISTS award_invitations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  token_hash CHAR(64) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL,
  event_year SMALLINT UNSIGNED NOT NULL,
  expires_at DATETIME NOT NULL,
  revoked_at DATETIME NULL,
  application_id BIGINT UNSIGNED NULL UNIQUE,
  otp_hash CHAR(64) NULL,
  otp_sent_at DATETIME NULL,
  otp_attempts TINYINT UNSIGNED NOT NULL DEFAULT 0,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (application_id) REFERENCES award_applications(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
